//! The TypeScript types committed in `bindings/` are the ones the Rust types generate, so a client
//! cannot drift from the runtime. With `BINDINGS=update`, the test rewrites them instead.

use std::collections::{BTreeMap, BTreeSet};
use std::path::Path;
use std::{env, fs, io};

use protocol::{ClientFrame, RuntimeFrame, VERSION};
use ts_rs::{Config, TS};

const COMMITTED: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/bindings");

#[test]
fn bindings_match_the_rust_types() {
    if env::var("BINDINGS").as_deref() == Ok("update") {
        generate(Path::new(COMMITTED));
        return;
    }
    let generated = Path::new(env!("CARGO_TARGET_TMPDIR")).join("bindings");
    generate(&generated);

    let (generated, committed) = (read(&generated), read(Path::new(COMMITTED)));
    let drifted: BTreeSet<_> = generated
        .keys()
        .chain(committed.keys())
        .filter(|name| generated.get(*name) != committed.get(*name))
        .collect();
    assert!(
        drifted.is_empty(),
        "{drifted:?} in bindings/ drifted from the Rust types; regenerate them with \
         `BINDINGS=update cargo test -p protocol --test bindings`"
    );
}

// Both frames reach every type of the contract.
fn generate(dir: &Path) {
    match fs::remove_dir_all(dir) {
        Err(error) if error.kind() != io::ErrorKind::NotFound => panic!("{error}"),
        _ => {}
    }
    let config = Config::new()
        .with_out_dir(dir)
        .with_import_extension(Some("ts"));
    ClientFrame::export_all(&config).unwrap();
    RuntimeFrame::export_all(&config).unwrap();
    // ts-rs exports types only; a client needs the version to send its `Hello`.
    fs::write(
        dir.join("version.ts"),
        format!(
            "// Generated from `protocol::VERSION` by `tests/bindings.rs`. Do not edit this file manually.\n\
             export const VERSION = {VERSION};\n"
        ),
    )
    .unwrap();
}

fn read(dir: &Path) -> BTreeMap<String, String> {
    let Ok(entries) = fs::read_dir(dir) else {
        return BTreeMap::new();
    };
    entries
        .map(|entry| {
            let path = entry.unwrap().path();
            let name = path.file_name().unwrap().to_string_lossy().into_owned();
            (name, fs::read_to_string(&path).unwrap())
        })
        .collect()
}
